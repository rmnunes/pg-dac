package projsync_test

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/rmnunes/pg-dac/internal/build"
	"github.com/rmnunes/pg-dac/internal/devdb"
	"github.com/rmnunes/pg-dac/internal/engine"
	"github.com/rmnunes/pg-dac/internal/introspect"
	"github.com/rmnunes/pg-dac/internal/model"
	"github.com/rmnunes/pg-dac/internal/project"
	"github.com/rmnunes/pg-dac/internal/projsync"
)

// The full loop on a real PostgreSQL: extract a database into a project, let
// the database move on (a column appended, a grant added, a view dropped, a
// function body changed, a new table), update the project from it, and the
// rebuilt project matches the database in both directions.
func TestUpdateProjectFromDatabaseRoundTrip(t *testing.T) {
	if testing.Short() {
		t.Skip("needs embedded postgres")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 6*time.Minute)
	defer cancel()
	ctx, cleanup := devdb.WithShared(ctx)
	defer cleanup()

	sc, err := devdb.Acquire(ctx, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer sc.Release()
	conn, err := pgx.Connect(ctx, sc.ConnString)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)

	exec := func(sql string) {
		t.Helper()
		if _, err := conn.Exec(ctx, sql); err != nil {
			t.Fatalf("%s: %v", sql, err)
		}
	}
	exec(`DO $$BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='ps_reader') THEN CREATE ROLE ps_reader NOLOGIN; END IF; END$$;
CREATE SCHEMA app;
CREATE TABLE app.t(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, a text);
CREATE VIEW app.v AS SELECT id FROM app.t;
CREATE VIEW app.gone AS SELECT a FROM app.t;
CREATE FUNCTION app.f() RETURNS int LANGUAGE sql AS 'SELECT 1';
COMMENT ON TABLE app.t IS 'the t table';`)

	canonical := func() *model.Database {
		t.Helper()
		raw, err := introspect.Introspect(ctx, conn, introspect.Options{})
		if err != nil {
			t.Fatal(err)
		}
		m, err := build.Canonicalize(ctx, raw, build.Options{})
		if err != nil {
			t.Fatal(err)
		}
		return m
	}

	// Extract into a project (what `extract --to-project` writes).
	before := canonical()
	dir := t.TempDir()
	for _, f := range engine.ProjectFiles(before) {
		p := filepath.Join(dir, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(f.SQL+"\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	man := project.Default("rt")
	man.Include = []string{engine.ExtensionsSection + "/**/*.sql", engine.ExtractSection + "/**/*.sql"}
	man.TargetMajor = before.MajorVersion()
	man.Roles = before.Grantees()
	man.DropPolicy = "all"
	if err := man.Save(dir); err != nil {
		t.Fatal(err)
	}
	tablePath := filepath.Join(dir, "schema", "app", "tables", "t.sql")
	if _, err := os.Stat(tablePath); err != nil {
		t.Fatalf("stable layout expected at %s: %v", tablePath, err)
	}
	// A hand edit that must survive: a comment above the table's statement.
	orig, _ := os.ReadFile(tablePath)
	if err := os.WriteFile(tablePath, []byte("-- Owned by team A\n"+string(orig)), 0o644); err != nil {
		t.Fatal(err)
	}

	// The database moves on.
	exec(`ALTER TABLE app.t ADD COLUMN b text;
GRANT SELECT ON app.t TO ps_reader;
DROP VIEW app.gone;
CREATE OR REPLACE FUNCTION app.f() RETURNS int LANGUAGE sql AS 'SELECT 2';
CREATE TABLE app.n(id int PRIMARY KEY);`)
	after := canonical()

	// Update the project from the database.
	man, err = project.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	fromProject, _, err := build.FromDir(ctx, dir, build.Options{})
	if err != nil {
		t.Fatalf("project does not build: %v", err)
	}
	opts := engine.DefaultOptions()
	opts.DropObjectsNotInSource = true
	res, err := engine.Compare(fromProject, after, opts)
	if err != nil {
		t.Fatal(err)
	}
	idx, err := projsync.Scan(dir, man, fromProject)
	if err != nil {
		t.Fatal(err)
	}
	plan, err := projsync.Build(idx, man, fromProject, after, res)
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.Refused) != 0 {
		t.Fatalf("unexpected refusals: %+v", plan.Refused)
	}
	actions := map[string]string{}
	for _, c := range plan.Changes {
		actions[c.Path] = c.Action
	}
	want := map[string]string{
		"schema/app/tables/t.sql":    "modify",
		"schema/app/views/gone.sql":  "delete",
		"schema/app/functions/f.sql": "modify",
		"schema/app/tables/n.sql":    "create",
	}
	for p, a := range want {
		if actions[p] != a {
			t.Errorf("%s: want %s, got %q (all: %v)", p, a, actions[p], actions)
		}
	}
	if len(plan.Changes) != len(want) {
		t.Errorf("unexpected extra changes: %v", actions)
	}
	if !strings.Contains(plan.Diff(), `+    "b" text`) {
		t.Errorf("diff should show the appended column:\n%s", plan.Diff())
	}
	if err := plan.Apply(); err != nil {
		t.Fatal(err)
	}
	updated, _ := os.ReadFile(tablePath)
	if !strings.HasPrefix(string(updated), "-- Owned by team A\n") {
		t.Errorf("the hand-written header must survive:\n%s", updated)
	}
	if !strings.Contains(string(updated), `GRANT SELECT ON TABLE "app"."t" TO "ps_reader";`) {
		t.Errorf("the grant must be in the table's file:\n%s", updated)
	}
	if man2, _ := project.Load(dir); len(man2.Roles) != 1 || man2.Roles[0] != "ps_reader" {
		t.Errorf("roles should list the grantee: %v", man2.Roles)
	}

	// The updated project builds and matches the database both ways.
	rebuilt, _, err := build.FromDir(ctx, dir, build.Options{})
	if err != nil {
		t.Fatalf("updated project does not build: %v", err)
	}
	if r, _ := engine.Compare(rebuilt, after, opts); !r.Empty() {
		t.Errorf("project still differs from the database:\n%s", r.Script(true))
	}
	if r, _ := engine.Compare(after, rebuilt, opts); !r.Empty() {
		t.Errorf("database still differs from the project:\n%s", r.Script(true))
	}
}
