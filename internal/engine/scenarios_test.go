// Expectation of a migration scenario against a real PostgreSQL:
//
//	ok    the generated migration applies and converges (attributes pg-dac does
//	      not model yet are silently dropped — see the audit notes §4.2 — but the
//	      migration itself is correct for everything it does model)
//	fail  the generated migration errors when applied — a KNOWN gap, listed with
//	      the work package that fixes it; when it starts passing, flip it to ok
//	miss  the two models differ but the differ emits nothing (unmodeled attribute)
//	noconv the migration applies but cannot converge: PostgreSQL has no in-place
//	      operation for the change, so pg-dac emits an UNSUPPORTED_CHANGE hazard
//	      (a RAISE WARNING) instead of silently doing nothing
const (
	ok     = "ok"
	fail   = "fail"
	miss   = "miss"
	noconv = "noconv"
)

type scenario struct {
	name   string
	from   string
	to     string
	expect string
	reason string
}

// role creates the grantee the privilege scenarios use; roles are cluster-wide
// on the shared scratch server, so creation is guarded.
const role = `DO $$BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='scn_reader') THEN CREATE ROLE scn_reader NOLOGIN; END IF; END$$;`

// scenarioMinMajor holds the scenarios that need a newer PostgreSQL than the
// oldest supported one; on an older scratch major (CI runs every supported
// major) they are skipped, not passed.
var scenarioMinMajor = map[string]int{
	"generated-column-expr-change": 12, // generated columns arrived in PG12
	"generated-to-plain":           12,
	"plain-to-generated":           12,
}

// skipBelowMinMajor skips a scenario the scratch major cannot express.
func skipBelowMinMajor(t *testing.T, name string) {
	t.Helper()
	if min := scenarioMinMajor[name]; devdb.DefaultMajor() < min {
		t.Skipf("needs PostgreSQL %d (scratch major is %d)", min, devdb.DefaultMajor())
	}
}

