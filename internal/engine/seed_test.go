// A column whose value generator changes on a populated table must keep
// generating values past the existing rows: converting a serial column to
// identity (and back) in a table with data, the next insert succeeds and
// continues the numbering instead of colliding on 1.
func TestSeedSequenceOnPopulatedTable(t *testing.T) {
	if testing.Short() {
		t.Skip("needs embedded postgres")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	ctx, cleanup := devdb.WithShared(ctx)
	defer cleanup()

	sc, err := devdb.Acquire(ctx, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer sc.Release()
	conn, err := pgx.Connect(ctx, sc.ConnString)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)

	mustExec(t, ctx, conn, `CREATE TABLE t(id serial PRIMARY KEY, v text); INSERT INTO t(v) VALUES ('a'), ('b'), ('c');`)

	opts := engine.DefaultOptions()
	opts.Online = false
	opts.AllowHazards = true
	opts.DropObjectsNotInSource = true

	// serial -> identity
	migrate(t, ctx, conn, `CREATE TABLE t(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text);`, opts, "deptype = 'i'")
	if got := insertReturningID(t, ctx, conn); got != 4 {
		t.Fatalf("after serial->identity the next id should be 4, got %d", got)
	}

	// identity -> serial (an explicit sequence of the same name the identity
	// sequence had: CREATE SEQUENCE must wait for DROP IDENTITY)
	migrate(t, ctx, conn, `CREATE SEQUENCE t_id_seq; CREATE TABLE t(id int PRIMARY KEY DEFAULT nextval('t_id_seq'), v text); ALTER SEQUENCE t_id_seq OWNED BY t.id;`, opts, "setval('public.t_id_seq'::regclass")
	if got := insertReturningID(t, ctx, conn); got != 5 {
		t.Fatalf("after identity->serial the next id should be 5, got %d", got)
	}

	// an existing plain column that gains a default on a brand-new sequence
	mustExec(t, ctx, conn, `ALTER TABLE t ADD COLUMN n integer; UPDATE t SET n = id * 10;`)
	migrate(t, ctx, conn, `CREATE SEQUENCE t_id_seq; CREATE SEQUENCE n_seq; CREATE TABLE t(id int PRIMARY KEY DEFAULT nextval('t_id_seq'), v text, n integer DEFAULT nextval('n_seq')); ALTER SEQUENCE t_id_seq OWNED BY t.id;`, opts, "setval('public.n_seq'::regclass")
	var n int
	if err := conn.QueryRow(ctx, `INSERT INTO t(v) VALUES ('f') RETURNING n`).Scan(&n); err != nil {
		t.Fatal(err)
	}
	if n != 51 {
		t.Fatalf("new default sequence should continue past max(n)=50, got %d", n)
	}
}

// migrate compares the live scratch database (canonicalized like any source)
// against the desired SQL, checks the script carries the expected seeding
// statement, and applies it.
func migrate(t *testing.T, ctx context.Context, conn *pgx.Conn, desired string, opts engine.Options, wantInScript string) {
	t.Helper()
	raw, err := introspect.Introspect(ctx, conn, introspect.Options{})
	if err != nil {
		t.Fatal(err)
	}
	from, err := build.Canonicalize(ctx, raw, build.Options{})
	if err != nil {
		t.Fatalf("canonicalize live model: %v", err)
	}
	to, _, err := build.FromSQL(ctx, desired, build.Options{})
	if err != nil {
		t.Fatalf("build desired: %v", err)
	}
	res, err := engine.Compare(from, to, opts)
	if err != nil {
		t.Fatal(err)
	}
	script := res.Script(true)
	if !strings.Contains(script, wantInScript) {
		t.Fatalf("script should contain %q:\n%s", wantInScript, script)
	}
	if err := execute.ApplyStatements(ctx, conn, res.Statements); err != nil {
		t.Fatalf("apply: %v\n--- script ---\n%s", err, script)
	}
	// Converged: a second compare is empty.
	raw2, err := introspect.Introspect(ctx, conn, introspect.Options{})
	if err != nil {
		t.Fatal(err)
	}
	from2, err := build.Canonicalize(ctx, raw2, build.Options{})
	if err != nil {
		t.Fatal(err)
	}
	again, err := engine.Compare(from2, to, opts)
	if err != nil {
		t.Fatal(err)
	}
	if !again.Empty() {
		t.Fatalf("did not converge; residual:\n%s", again.Script(true))
	}
}

func insertReturningID(t *testing.T, ctx context.Context, conn *pgx.Conn) int {
	t.Helper()
	var id int
	if err := conn.QueryRow(ctx, `INSERT INTO t(v) VALUES ('x') RETURNING id`).Scan(&id); err != nil {
		t.Fatalf("insert after migration: %v", err)
	}
	return id
}

func mustExec(t *testing.T, ctx context.Context, conn *pgx.Conn, sql string) {
	t.Helper()
	if _, err := conn.Exec(ctx, sql); err != nil {
		t.Fatalf("%s: %v", sql, err)
	}
}

