package engine_test

import (
	"context"
	"strings"
	"testing"
	"time"

	"github.com/jackc/pgx/v5"

	"github.com/rmnunes/pg-dac/internal/build"
	"github.com/rmnunes/pg-dac/internal/devdb"
	"github.com/rmnunes/pg-dac/internal/engine"
	"github.com/rmnunes/pg-dac/internal/execute"
	"github.com/rmnunes/pg-dac/internal/introspect"
)

// A table rebuild on a real PostgreSQL: rows, identity numbering, a serial
// sequence, a foreign key from another table, a view, a trigger and a grant
// all survive the swap, the declared column order is reached, and the model
// converges.
func TestRebuildTableOnPopulatedDatabase(t *testing.T) {
	if testing.Short() {
		t.Skip("needs embedded postgres")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	ctx, cleanup := devdb.WithShared(ctx)
	defer cleanup()

	sc, err := devdb.Acquire(ctx, 0)
	if err != nil {
		t.Fatal(err)
	}
	defer sc.Release()
	conn, err := pgx.Connect(ctx, sc.ConnString)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(ctx)

	const role = `DO $$BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='rb_reader') THEN CREATE ROLE rb_reader NOLOGIN; END IF; END$$;`
	const common = `
CREATE FUNCTION tf() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN NEW.b := upper(NEW.b); RETURN NEW; END$$;
CREATE TABLE child(id int PRIMARY KEY, t_id int REFERENCES t(id));
CREATE VIEW v AS SELECT id, b FROM t;
CREATE TRIGGER tg BEFORE INSERT ON t FOR EACH ROW EXECUTE FUNCTION tf();
GRANT SELECT ON t TO rb_reader;
GRANT SELECT ON v TO rb_reader;`

	// The target: columns appended over time, so the physical order is id, b, n, a.
	mustExec(t, ctx, conn, role+`
CREATE SEQUENCE n_seq;
CREATE TABLE t(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, b text, n int DEFAULT nextval('n_seq'), a text);
ALTER SEQUENCE n_seq OWNED BY t.n;`+common+`
INSERT INTO t(b, a) VALUES ('x', 'A1'), ('y', 'A2'), ('z', 'A3');
INSERT INTO child VALUES (1, 1), (2, 3);`)

	// The source declares id, a, b, n.
	desired := role + `
CREATE SEQUENCE n_seq;
CREATE TABLE t(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, a text, b text, n int DEFAULT nextval('n_seq'));
ALTER SEQUENCE n_seq OWNED BY t.n;` + common

	raw, err := introspect.Introspect(ctx, conn, introspect.Options{})
	if err != nil {
		t.Fatal(err)
	}
	from, err := build.Canonicalize(ctx, raw, build.Options{})
	if err != nil {
		t.Fatal(err)
	}
	to, _, err := build.FromSQL(ctx, desired, build.Options{})
	if err != nil {
		t.Fatalf("build desired: %v", err)
	}

	// Default policy: a warning, no rebuild, nothing to apply.
	warnOnly, err := engine.Compare(from, to, engine.DefaultOptions())
	if err != nil {
		t.Fatal(err)
	}
	if !warnOnly.Empty() || len(warnOnly.Warnings) != 1 || !strings.Contains(warnOnly.Warnings[0], "column order") {
		t.Fatalf("default policy must only warn; ops:\n%s\nwarnings: %v", warnOnly.Script(true), warnOnly.Warnings)
	}

	opts := engine.DefaultOptions()
	opts.Online = false
	opts.ColumnOrder = "rebuild"
	res, err := engine.Compare(from, to, opts)
	if err != nil {
		t.Fatal(err)
	}
	if res.HasDataLoss() {
		t.Fatalf("no data loss expected:\n%s", res.Script(true))
	}
	if err := execute.ApplyStatements(ctx, conn, res.Statements); err != nil {
		t.Fatalf("apply rebuild: %v\n--- script ---\n%s", err, res.Script(true))
	}

	var order string
	if err := conn.QueryRow(ctx, `SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid='t'::regclass AND attnum > 0 AND NOT attisdropped`).Scan(&order); err != nil {
		t.Fatal(err)
	}
	if order != "id,a,b,n" {
		t.Fatalf("column order after rebuild: %s", order)
	}
	var rows int
	var data string
	if err := conn.QueryRow(ctx, `SELECT count(*), string_agg(id || ':' || b || ':' || a || ':' || n, ' ' ORDER BY id) FROM t`).Scan(&rows, &data); err != nil {
		t.Fatal(err)
	}
	if rows != 3 || data != "1:X:A1:1 2:Y:A2:2 3:Z:A3:3" {
		t.Fatalf("rows after rebuild: %d %q", rows, data)
	}
	var id, n int
	if err := conn.QueryRow(ctx, `INSERT INTO t(b, a) VALUES ('w', 'A4') RETURNING id, n`).Scan(&id, &n); err != nil {
		t.Fatalf("insert after rebuild: %v", err)
	}
	if id != 4 || n != 4 {
		t.Fatalf("generators must continue: id=%d n=%d", id, n)
	}
	var upper string
	if err := conn.QueryRow(ctx, `SELECT b FROM t WHERE id = 4`).Scan(&upper); err != nil || upper != "W" {
		t.Fatalf("trigger must survive: b=%q err=%v", upper, err)
	}
	if _, err := conn.Exec(ctx, `INSERT INTO child VALUES (3, 99)`); err == nil {
		t.Fatal("foreign key must be enforced after the rebuild")
	}
	var canRead bool
	if err := conn.QueryRow(ctx, `SELECT has_table_privilege('rb_reader', 't', 'SELECT')`).Scan(&canRead); err != nil || !canRead {
		t.Fatalf("grant must survive: %v %v", canRead, err)
	}
	var viewRows int
	if err := conn.QueryRow(ctx, `SELECT count(*) FROM v`).Scan(&viewRows); err != nil || viewRows != 4 {
		t.Fatalf("view must work after the rebuild: %d %v", viewRows, err)
	}

	raw2, err := introspect.Introspect(ctx, conn, introspect.Options{})
	if err != nil {
		t.Fatal(err)
	}
	from2, err := build.Canonicalize(ctx, raw2, build.Options{})
	if err != nil {
		t.Fatal(err)
	}
	again, err := engine.Compare(from2, to, opts)
	if err != nil {
		t.Fatal(err)
	}
	if !again.Empty() || len(again.Warnings) != 0 {
		t.Fatalf("did not converge; residual:\n%s\nwarnings: %v", again.Script(true), again.Warnings)
	}
}
