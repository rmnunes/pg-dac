// columnDef renders a single column definition for CREATE TABLE / ADD COLUMN.
func columnDef(c *model.Column) string {
	var b strings.Builder
	b.WriteString(model.QuoteIdent(c.Name))
	b.WriteString(" ")
	b.WriteString(c.Type)
	if c.Collation != "" {
		b.WriteString(" COLLATE " + c.Collation)
	}
	switch {
	case c.Generated == "stored" && c.GeneratedExpr != "":
		b.WriteString(" GENERATED ALWAYS AS (" + c.GeneratedExpr + ") STORED")
	case c.Generated == "virtual" && c.GeneratedExpr != "":
		b.WriteString(" GENERATED ALWAYS AS (" + c.GeneratedExpr + ") VIRTUAL")
	case c.Identity == "always":
		b.WriteString(" GENERATED ALWAYS AS IDENTITY")
	case c.Identity == "byDefault":
		b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
	case c.Default != "":
		b.WriteString(" DEFAULT " + c.Default)
	}
	if c.NotNull {
		b.WriteString(" NOT NULL")
	}
	return b.String()
}

func renderCreateTable(t *model.Table) []Statement {
	keyword := "TABLE"
	if t.Persistence == "unlogged" {
		keyword = "UNLOGGED TABLE"
	}
	var sql string
	if t.PartitionOf != nil {
		// A partition inherits its columns from the parent.
		sql = "CREATE " + keyword + " " + t.QualifiedName() + " PARTITION OF " +
			model.QualifiedName(t.PartitionOf.Schema, t.PartitionOf.Table) + " " + t.PartitionOf.Bound
	} else {
		lines := make([]string, 0, len(t.Columns))
		for _, c := range t.Columns {
			lines = append(lines, "    "+columnDef(c))
		}
		sql = "CREATE " + keyword + " " + t.QualifiedName() + " (\n" + strings.Join(lines, ",\n") + "\n)"
		if t.PartitionKey != "" {
			sql += " PARTITION BY " + t.PartitionKey
		}
	}
	if len(t.RelOptions) > 0 {
		sql += " WITH (" + renderRelOptions(t.RelOptions) + ")"
	}
	stmts := []Statement{{SQL: sql + ";", Transactional: true}}
	stmts = append(stmts, commentOn("TABLE", t.QualifiedName(), t.Comment)...)
	for _, c := range t.Columns {
		stmts = append(stmts, commentOn("COLUMN", t.QualifiedName()+"."+model.QuoteIdent(c.Name), c.Comment)...)
	}
	return stmts
}

func renderRelOptions(opts map[string]string) string {
	keys := make([]string, 0, len(opts))
	for k := range opts {
		keys = append(keys, k)
	}
	// deterministic order
	for i := 1; i < len(keys); i++ {
		for j := i; j > 0 && keys[j] < keys[j-1]; j-- {
			keys[j], keys[j-1] = keys[j-1], keys[j]
		}
	}
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = k + "=" + opts[k]
	}
	return strings.Join(parts, ", ")
}

func renderAddColumn(op diff.Op, opts Options) []Statement {
	c := op.Column
	s := Statement{
		SQL:           "ALTER TABLE " + op.Table.QualifiedName() + " ADD COLUMN " + columnDef(c) + ";",
		Transactional: true,
		Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table")},
	}
	if c.NotNull && c.Default == "" && c.Identity == "" && c.Generated == "" {
		s.Hazards = append(s.Hazards, safety.New(safety.Correctness,
			"adding a NOT NULL column without a default fails on a non-empty table"))
	}
	if c.Default != "" && !safety.MetadataOnlyAddColumn(opts.TargetMajor) {
		s.Hazards = append(s.Hazards, safety.New(safety.TableRewrite,
			"adding a column with a default rewrites the table before PostgreSQL 11"))
	}
	stmts := []Statement{s}
	stmts = append(stmts, commentOn("COLUMN", op.Table.QualifiedName()+"."+model.QuoteIdent(c.Name), c.Comment)...)
	return stmts
}

func renderAlterColumnType(op diff.Op) []Statement {
	c := op.Column
	sql := "ALTER TABLE " + op.Table.QualifiedName() + " ALTER COLUMN " + model.QuoteIdent(c.Name) + " TYPE " + c.Type
	if c.Collation != "" {
		sql += " COLLATE " + c.Collation
	}
	// An explicit cast lets conversions with no assignment cast (text -> integer,
	// ...) apply; for binary-coercible changes PostgreSQL still skips the rewrite.
	sql += " USING " + model.QuoteIdent(c.Name) + "::" + c.Type
	return []Statement{{
		SQL:           sql + ";",
		Transactional: true,
		Note:          "type changes rewrite the table unless the cast is binary-coercible; the USING cast is a plain conversion — edit it if values need transforming",
		Hazards: []safety.Hazard{
			safety.New(safety.TableRewrite, "may rewrite the whole table and its indexes"),
			safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table"),
		},
	}}
}

func renderSetNotNull(op diff.Op, opts Options) []Statement {
	t := op.Table
	col := op.Column.Name
	if !opts.Online || !safety.ScanFreeSetNotNull(opts.TargetMajor) {
		return []Statement{{
			SQL:           "ALTER TABLE " + t.QualifiedName() + " ALTER COLUMN " + model.QuoteIdent(col) + " SET NOT NULL;",
			Transactional: true,
			Hazards: []safety.Hazard{
				safety.New(safety.AccessExclusiveLock, "scans the whole table under ACCESS EXCLUSIVE to verify no NULLs"),
			},
		}}
	}
	// Online (PG12+): validate via a CHECK constraint so SET NOT NULL is scan-free.
	cname := genName("pgdac_nn", t.Name, col)
	q := model.QuoteIdent(cname)
	return []Statement{
		{
			SQL:           "ALTER TABLE " + t.QualifiedName() + " ADD CONSTRAINT " + q + " CHECK (" + model.QuoteIdent(col) + " IS NOT NULL) NOT VALID;",
			Transactional: true,
			Note:          "stage NOT NULL safely: add an unvalidated CHECK first (brief lock, no scan)",
		},
		{
			SQL:           "ALTER TABLE " + t.QualifiedName() + " VALIDATE CONSTRAINT " + q + ";",
			Transactional: true,
			Note:          "validate the CHECK (SHARE UPDATE EXCLUSIVE — does not block writes)",
		},
		{
			SQL:           "ALTER TABLE " + t.QualifiedName() + " ALTER COLUMN " + model.QuoteIdent(col) + " SET NOT NULL;",
			Transactional: true,
			Note:          "scan-free on PG12+ because a validated CHECK proves no NULLs",
			Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "brief ACCESS EXCLUSIVE (no scan)")},
		},
		{
			SQL:           "ALTER TABLE " + t.QualifiedName() + " DROP CONSTRAINT " + q + ";",
			Transactional: true,
			Note:          "drop the now-redundant staging CHECK",
		},
	}
}

func renderAddConstraint(op diff.Op, opts Options) []Statement {
	t := op.Table
	con := op.Constraint
	q := model.QuoteIdent(con.Name)
	base := "ALTER TABLE " + t.QualifiedName() + " ADD CONSTRAINT " + q + " " + con.Definition

	comment := commentOn("CONSTRAINT", q+" ON "+t.QualifiedName(), con.Comment)

	switch con.Type {
	case model.ConstraintForeignKey, model.ConstraintCheck:
		if !con.Validated {
			// The desired state itself keeps the constraint unvalidated.
			return append([]Statement{{
				SQL:           base + " NOT VALID;",
				Transactional: true,
				Note:          "the source holds this constraint NOT VALID; it is added unvalidated and not validated",
				Hazards:       []safety.Hazard{safety.New(safety.ShareRowExclusiveLock, "brief lock to add the constraint (no scan)")},
			}}, comment...)
		}
		if opts.Online {
			lock := safety.ShareRowExclusiveLock
			if con.Type == model.ConstraintCheck {
				lock = safety.AccessExclusiveLock
			}
			return append([]Statement{
				{
					SQL:           base + " NOT VALID;",
					Transactional: true,
					Note:          "add unvalidated first to skip the blocking full-table scan",
					Hazards:       []safety.Hazard{safety.New(lock, "brief lock to add the constraint (no scan)")},
				},
				{
					SQL:           "ALTER TABLE " + t.QualifiedName() + " VALIDATE CONSTRAINT " + q + ";",
					Transactional: true,
					Note:          "validate separately (SHARE UPDATE EXCLUSIVE — does not block writes)",
				},
			}, comment...)
		}
		return append([]Statement{{SQL: base + ";", Transactional: true,
			Hazards: []safety.Hazard{safety.New(safety.AccessExclusiveLock, "scans the table to validate the constraint")}}}, comment...)

	case model.ConstraintPrimaryKey, model.ConstraintUnique, model.ConstraintExclude:
		note := ""
		if con.Type == model.ConstraintUnique && opts.Online {
			note = "a lower-lock path exists: CREATE UNIQUE INDEX CONCURRENTLY then ADD CONSTRAINT ... USING INDEX"
		}
		return append([]Statement{{SQL: base + ";", Transactional: true, Note: note,
			Hazards: []safety.Hazard{
				safety.New(safety.AccessExclusiveLock, "builds the backing index under ACCESS EXCLUSIVE"),
				safety.New(safety.IndexBuild, "builds an index"),
			}}}, comment...)
	}
	return append([]Statement{{SQL: base + ";", Transactional: true}}, comment...)
}

func renderCreateIndex(op diff.Op, opts Options) []Statement {
	def := strings.TrimRight(op.Index.Definition, ";")
	comment := commentOn("INDEX", model.QualifiedName(op.Owner.Schema, op.Index.Name), op.Index.Comment)
	if opts.Online {
		return append([]Statement{{
			SQL:           concurrentIndexDef(def) + ";",
			Transactional: false,
			Note:          "CONCURRENTLY: builds without blocking writes; cannot run inside a transaction",
			Hazards:       []safety.Hazard{safety.New(safety.IndexBuild, "builds an index")},
		}}, comment...)
	}
	return append([]Statement{{
		SQL:           def + ";",
		Transactional: true,
		Hazards: []safety.Hazard{
			safety.New(safety.ShareLock, "blocks writes on the table while the index builds"),
			safety.New(safety.IndexBuild, "builds an index"),
		},
	}}, comment...)
}

func renderDropIndex(op diff.Op, opts Options) []Statement {
	name := model.QualifiedName(op.Owner.Schema, op.Index.Name)
	if opts.Online {
		return []Statement{{
			SQL:           "DROP INDEX CONCURRENTLY " + name + ";",
			Transactional: false,
			Hazards:       []safety.Hazard{safety.New(safety.IndexDropped, "removes an index")},
		}}
	}
	return []Statement{{
		SQL:           "DROP INDEX " + name + ";",
		Transactional: true,
		Hazards: []safety.Hazard{
			safety.New(safety.IndexDropped, "removes an index"),
			safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table"),
		},
	}}
}

func renderCreateSequence(s *model.Sequence) string {
	var b strings.Builder
	b.WriteString("CREATE SEQUENCE " + s.QualifiedName())
	if s.DataType != "" {
		b.WriteString(" AS " + s.DataType)
	}
	if s.Increment != 0 {
		b.WriteString(" INCREMENT BY " + strconv.FormatInt(s.Increment, 10))
	}
	if s.MinValue != 0 {
		b.WriteString(" MINVALUE " + strconv.FormatInt(s.MinValue, 10))
	}
	if s.MaxValue != 0 {
		b.WriteString(" MAXVALUE " + strconv.FormatInt(s.MaxValue, 10))
	}
	if s.Start != 0 {
		b.WriteString(" START WITH " + strconv.FormatInt(s.Start, 10))
	}
	if s.Cache > 0 {
		b.WriteString(" CACHE " + strconv.FormatInt(s.Cache, 10))
	}
	if s.Cycle {
		b.WriteString(" CYCLE")
	}
	return b.String() + ";"
}

func renderAlterSequence(s *model.Sequence) string {
	var b strings.Builder
	b.WriteString("ALTER SEQUENCE " + s.QualifiedName())
	if s.Increment != 0 {
		b.WriteString(" INCREMENT BY " + strconv.FormatInt(s.Increment, 10))
	}
	if s.MinValue != 0 {
		b.WriteString(" MINVALUE " + strconv.FormatInt(s.MinValue, 10))
	}
	if s.MaxValue != 0 {
		b.WriteString(" MAXVALUE " + strconv.FormatInt(s.MaxValue, 10))
	}
	if s.Cache > 0 {
		b.WriteString(" CACHE " + strconv.FormatInt(s.Cache, 10))
	}
	if s.Cycle {
		b.WriteString(" CYCLE")
	} else {
		b.WriteString(" NO CYCLE")
	}
	return b.String() + ";"
}

// renderSequenceOwner attaches (or detaches) a sequence to the column that
// owns it, so the sequence is dropped with the column like a serial's.
func renderSequenceOwner(s *model.Sequence) string {
	if s.OwnedBy == nil {
		return "ALTER SEQUENCE " + s.QualifiedName() + " OWNED BY NONE;"
	}
	return "ALTER SEQUENCE " + s.QualifiedName() + " OWNED BY " +
		model.QualifiedName(s.OwnedBy.Schema, s.OwnedBy.Table) + "." + model.QuoteIdent(s.OwnedBy.Column) + ";"
}

func concurrentIndexDef(def string) string {
	switch {
	case strings.HasPrefix(def, "CREATE UNIQUE INDEX "):
		return "CREATE UNIQUE INDEX CONCURRENTLY " + def[len("CREATE UNIQUE INDEX "):]
	case strings.HasPrefix(def, "CREATE INDEX "):
		return "CREATE INDEX CONCURRENTLY " + def[len("CREATE INDEX "):]
	}
	return def
}

// renderAlterColumnIdentity reconciles a column's identity attribute, including
// the common legacy conversion from a serial-style default to an identity column.
func renderAlterColumnIdentity(op diff.Op) []Statement {
	t := op.Table.QualifiedName()
	col := model.QuoteIdent(op.Column.Name)
	prev, cur := op.PrevColumn, op.Column
	var stmts []Statement

	switch {
	case prev.Identity == "" && cur.Identity != "":
		// none -> identity. Drop any existing (serial) default first; a column
		// cannot have both a default and an identity.
		if prev.Default != "" {
			stmts = append(stmts, Statement{
				SQL:           "ALTER TABLE " + t + " ALTER COLUMN " + col + " DROP DEFAULT;",
				Transactional: true,
				Note:          "remove the existing default before adding identity (a column cannot have both)",
			})
		}
		conv := Statement{
			SQL:           "ALTER TABLE " + t + " ALTER COLUMN " + col + " ADD GENERATED " + identityKeyword(cur.Identity) + " AS IDENTITY;",
			Transactional: true,
			Note:          "convert to an identity column",
			Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table")},
		}
		if !op.SeedSequence {
			conv.Hazards = append(conv.Hazards, safety.New(safety.Correctness,
				"on a populated column, set the identity sequence past the existing maximum value to avoid collisions"))
		}
		stmts = append(stmts, conv)
		if op.SeedSequence {
			stmts = append(stmts, seedSequence(op.Table, cur.Name, identitySequenceExpr(op.Table, cur.Name)))
		}

	case prev.Identity != "" && cur.Identity == "":
		// Any default the desired column carries is set by its own op, ordered
		// after this one and after the sequence it may draw from exists.
		stmts = append(stmts, Statement{
			SQL:           "ALTER TABLE " + t + " ALTER COLUMN " + col + " DROP IDENTITY IF EXISTS;",
			Transactional: true,
			Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table")},
		})

	default: // both identity, kind differs (always <-> by default)
		stmts = append(stmts, Statement{
			SQL:           "ALTER TABLE " + t + " ALTER COLUMN " + col + " SET GENERATED " + identityKeyword(cur.Identity) + ";",
			Transactional: true,
		})
	}
	return stmts
}

func identityKeyword(identity string) string {
	if identity == "always" {
		return "ALWAYS"
	}
	return "BY DEFAULT"
}

// seedSequence positions a sequence that has never seen the column's rows just
// past the column's current maximum, so the next generated value cannot
// collide with existing data. seqExpr yields the sequence (a regclass). An
// empty table seeds to 1; a missing sequence (NULL regclass) is a no-op.
func seedSequence(t *model.Table, col, seqExpr string) Statement {
	q := model.QuoteIdent(col)
	return Statement{
		SQL: "SELECT pg_catalog.setval(" + seqExpr + ", COALESCE((SELECT max(" + q + ") FROM " + t.QualifiedName() + "), 0) + 1, false);",
		Transactional: true,
		Note:          "seed the new sequence past the column's current maximum so generated values cannot collide with existing rows",
	}
}

// identitySequenceExpr yields the regclass of the identity sequence behind a
// column. pg_get_serial_sequence cannot be used: while the column's former
// serial sequence is still OWNED BY it (it is dropped later, or kept by the
// drop policy), that function may return the old sequence instead. An identity
// sequence is the one pg_depend links to the column with deptype 'i'.
func identitySequenceExpr(t *model.Table, col string) string {
	return "(SELECT d.objid::regclass FROM pg_catalog.pg_depend d " +
		"JOIN pg_catalog.pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid " +
		"WHERE d.classid = 'pg_catalog.pg_class'::regclass AND d.refclassid = 'pg_catalog.pg_class'::regclass " +
		"AND d.deptype = 'i' AND d.refobjid = " + model.QuoteLiteral(t.QualifiedName()) + "::regclass AND a.attname = " + model.QuoteLiteral(col) + ")"
}

// seedDefaultSequence seeds the sequence a column's new nextval() default draws
// from, when the differ flagged that sequence as new to the target.
func seedDefaultSequence(op diff.Op) []Statement {
	seq, ok := regclassOfDefault(op.Column.Default)
	if !ok {
		return nil
	}
	return []Statement{seedSequence(op.Table, op.Column.Name, seq)}
}

// regclassOfDefault turns a canonical nextval('x'::regclass) default into the
// 'x'::regclass expression naming its sequence.
func regclassOfDefault(def string) (string, bool) {
	const prefix, suffix = "nextval(", ")"
	if !strings.HasPrefix(def, prefix) || !strings.HasSuffix(def, suffix) {
		return "", false
	}
	inner := def[len(prefix) : len(def)-len(suffix)]
	if !strings.HasSuffix(inner, "::regclass") {
		return "", false
	}
	return inner, true
}

func renderCreatePolicy(op diff.Op) []Statement {
	p := op.Policy
	var b strings.Builder
	b.WriteString("CREATE POLICY " + model.QuoteIdent(p.Name) + " ON " + op.Table.QualifiedName())
	if !p.Permissive {
		b.WriteString(" AS RESTRICTIVE")
	}
	if p.Command != "" && strings.ToUpper(p.Command) != "ALL" {
		b.WriteString(" FOR " + strings.ToUpper(p.Command))
	}
	if len(p.Roles) > 0 {
		quoted := make([]string, len(p.Roles))
		for i, r := range p.Roles {
			quoted[i] = model.QuoteIdent(r)
		}
		b.WriteString(" TO " + strings.Join(quoted, ", "))
	}
	if p.Using != "" {
		b.WriteString(" USING (" + p.Using + ")")
	}
	if p.WithCheck != "" {
		b.WriteString(" WITH CHECK (" + p.WithCheck + ")")
	}
	b.WriteString(";")
	return one(b.String(), p.Comment, commentOn("POLICY", model.QuoteIdent(p.Name)+" ON "+op.Table.QualifiedName(), p.Comment))
}

func renderEnableRLS(op diff.Op) []Statement {
	t := op.Table
	stmts := []Statement{{
		SQL:           "ALTER TABLE " + t.QualifiedName() + " ENABLE ROW LEVEL SECURITY;",
		Transactional: true,
	}}
	force := "NO FORCE"
	if t.RLSForced {
		force = "FORCE"
	}
	stmts = append(stmts, Statement{
		SQL:           "ALTER TABLE " + t.QualifiedName() + " " + force + " ROW LEVEL SECURITY;",
		Transactional: true,
	})
	return stmts
}

// terminate ensures a statement ends with a single semicolon.
func terminate(sql string) string {
	s := strings.TrimRight(strings.TrimSpace(sql), ";")
	return s + ";"
}

// genName builds a deterministic, length-bounded identifier for a generated
// staging object (PostgreSQL truncates identifiers at 63 bytes).
func genName(prefix, a, b string) string {
	name := fmt.Sprintf("%s_%s_%s", prefix, a, b)
	if len(name) > 63 {
		name = name[:63]
	}
	return name
}

// --- WP3: table/column attributes, trigger state, comments, unsupported changes ---

func renderSetLogged(op diff.Op) []Statement {
	mode := "LOGGED"
	if op.Table.Persistence == "unlogged" {
		mode = "UNLOGGED"
	}
	return []Statement{{
		SQL:           "ALTER TABLE " + op.Table.QualifiedName() + " SET " + mode + ";",
		Transactional: true,
		Hazards: []safety.Hazard{
			safety.New(safety.TableRewrite, "changing a table's persistence rewrites it"),
			safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table"),
		},
	}}
}

func renderRelOptionsChange(op diff.Op) []Statement {
	var stmts []Statement
	if len(op.RelOptions) > 0 {
		stmts = append(stmts, Statement{
			SQL:           "ALTER TABLE " + op.Table.QualifiedName() + " SET (" + renderRelOptions(op.RelOptions) + ");",
			Transactional: true,
			Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "brief ACCESS EXCLUSIVE to change storage parameters")},
		})
	}
	if len(op.RelOptionsReset) > 0 {
		stmts = append(stmts, Statement{
			SQL:           "ALTER TABLE " + op.Table.QualifiedName() + " RESET (" + strings.Join(op.RelOptionsReset, ", ") + ");",
			Transactional: true,
			Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "brief ACCESS EXCLUSIVE to change storage parameters")},
		})
	}
	return stmts
}

func renderColumnAttr(op diff.Op) []Statement {
	base := "ALTER TABLE " + op.Table.QualifiedName() + " ALTER COLUMN " + model.QuoteIdent(op.Column.Name)
	var sql string
	switch op.Type {
	case diff.OpSetColumnStorage:
		v := "DEFAULT"
		if op.Column.Storage != "" {
			v = strings.ToUpper(op.Column.Storage)
		}
		sql = base + " SET STORAGE " + v
	case diff.OpSetColumnCompression:
		v := "DEFAULT"
		if op.Column.Compression != "" {
			v = op.Column.Compression
		}
		sql = base + " SET COMPRESSION " + v
	default:
		v := "-1"
		if op.Column.StatsTarget != nil {
			v = strconv.Itoa(*op.Column.StatsTarget)
		}
		sql = base + " SET STATISTICS " + v
	}
	return []Statement{{SQL: sql + ";", Transactional: true}}
}

// renderAlterGenerated reconciles a column's generation expression. PG17+ can
// edit the expression in place and PG13+ can drop it; anything else — and
// turning a plain column into a generated one — means dropping and re-adding
// the column.
func renderAlterGenerated(op diff.Op, opts Options) []Statement {
	prev, cur := op.PrevColumn, op.Column
	t := op.Table.QualifiedName()
	col := model.QuoteIdent(cur.Name)
	if prev != nil && prev.Generated != "" && cur.Generated == prev.Generated && opts.TargetMajor >= 17 {
		return []Statement{{
			SQL:           "ALTER TABLE " + t + " ALTER COLUMN " + col + " SET EXPRESSION AS (" + cur.GeneratedExpr + ");",
			Transactional: true,
			Note:          "generation expression changed; stored values are recomputed",
			Hazards: []safety.Hazard{
				safety.New(safety.TableRewrite, "recomputes the generated column for every row"),
				safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table"),
			},
		}}
	}
	if prev != nil && prev.Generated != "" && cur.Generated == "" && opts.TargetMajor >= 13 {
		return []Statement{{
			SQL:           "ALTER TABLE " + t + " ALTER COLUMN " + col + " DROP EXPRESSION;",
			Transactional: true,
			Note:          "the column stops being generated and keeps its current values",
			Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table")},
		}}
	}
	drop := Statement{
		SQL:           "ALTER TABLE " + t + " DROP COLUMN " + col + ";",
		Transactional: true,
		Note:          "the generation of this column changed in a way PostgreSQL cannot alter in place: the column is dropped and re-added",
		Hazards:       []safety.Hazard{safety.New(safety.AccessExclusiveLock, "takes ACCESS EXCLUSIVE on the table")},
	}
	if prev != nil && prev.Generated == "" {
		drop.Hazards = append(drop.Hazards, safety.New(safety.DeletesData, "the column's existing values are lost when it becomes generated"))
	} else {
		drop.Hazards = append(drop.Hazards, safety.New(safety.TableRewrite, "the generated values are recomputed for every row"))
	}
	return []Statement{drop, {
		SQL:           "ALTER TABLE " + t + " ADD COLUMN " + columnDef(cur) + ";",
		Transactional: true,
	}}
}

func renderTriggerEnabled(op diff.Op) []Statement {
	var mode string
	switch op.Trigger.Enabled {
	case "disabled":
		mode = "DISABLE"
	case "replica":
		mode = "ENABLE REPLICA"
	case "always":
		mode = "ENABLE ALWAYS"
	default:
		mode = "ENABLE"
	}
	return []Statement{{
		SQL:           "ALTER TABLE " + relName(op) + " " + mode + " TRIGGER " + model.QuoteIdent(op.Trigger.Name) + ";",
		Transactional: true,
	}}
}

// renderComment renders COMMENT ON for an object or one of its sub-objects.
func renderComment(op diff.Op) []Statement {
	owner := op.Owner
	qn := model.QualifiedName(owner.Schema, owner.Name)
	var spec string
	switch op.CommentKind {
	case "column":
		spec = "COLUMN " + qn + "." + model.QuoteIdent(op.Sub)
	case "constraint":
		spec = "CONSTRAINT " + model.QuoteIdent(op.Sub) + " ON " + qn
	case "index":
		spec = "INDEX " + model.QualifiedName(owner.Schema, op.Sub)
	case "trigger":
		spec = "TRIGGER " + model.QuoteIdent(op.Sub) + " ON " + qn
	case "policy":
		spec = "POLICY " + model.QuoteIdent(op.Sub) + " ON " + qn
	default:
		switch owner.Kind {
		case model.KindSchema:
			spec = "SCHEMA " + model.QuoteIdent(owner.Name)
		case model.KindTable:
			spec = "TABLE " + qn
		case model.KindView:
			spec = "VIEW " + qn
		case model.KindMatView:
			spec = "MATERIALIZED VIEW " + qn
		case model.KindSequence:
			spec = "SEQUENCE " + qn
		case model.KindEnum, model.KindComposite:
			spec = "TYPE " + qn
		case model.KindDomain:
			spec = "DOMAIN " + qn
		case model.KindCollation:
			spec = "COLLATION " + qn
		case model.KindFunction:
			// Owner.Name is "name(identity args)"; ROUTINE covers functions and procedures.
			name, args := owner.Name, ""
			if p := strings.IndexByte(name, '('); p >= 0 {
				name, args = name[:p], name[p:]
			}
			spec = "ROUTINE " + model.QualifiedName(owner.Schema, name) + args
		default:
			spec = string(owner.Kind) + " " + qn
		}
	}
	body := "NULL"
	if op.Comment != "" {
		body = model.QuoteLiteral(op.Comment)
	}
	return []Statement{{SQL: "COMMENT ON " + spec + " IS " + body + ";", Transactional: true}}
}

// renderUnsupported renders a change PostgreSQL cannot make in place as a
// RAISE WARNING so the script is honest about not converging, carrying an
// error-severity hazard that blocks publish unless hazards are allowed.
func renderUnsupported(op diff.Op) []Statement {
	msg := strings.ReplaceAll(op.Reason, "'", "''")
	return []Statement{{
		SQL:           "DO $$ BEGIN RAISE WARNING 'pg-dac: " + msg + "'; END $$;",
		Transactional: true,
		Hazards:       []safety.Hazard{safety.New(safety.Unsupported, op.Reason)},
	}}
}
